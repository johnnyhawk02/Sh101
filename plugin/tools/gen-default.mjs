// Writes plugin/src/DefaultPatch.h: the messages the web app sends the engine when it boots with no saved sound
// (pushAll in site/js/app/audio.js for the default state in state.js and seq.js), and the MIDI CC map from midi.js.
// A plugin instance whose editor has never been opened plays exactly this. Run after changing the web app's
// defaults:  node plugin/tools/gen-default.mjs
import vm from 'node:vm';
import { readFileSync, writeFileSync } from 'node:fs';
const site = new URL('../../site/', import.meta.url), out = new URL('../src/DefaultPatch.h', import.meta.url);
const ctx = { console, localStorage: { getItem: () => null, setItem() {} }, window: { addEventListener() {} }, document: { getElementById: () => ({}) } };
vm.createContext(ctx);
const src = ['defs', 'state', 'seq'].map((f) => readFileSync(new URL(`js/app/${f}.js`, site), 'utf8')).join('\n') + `
;globalThis.__out = { boot: [{ type: 'os', n: 2 }, { type: 'params', p: state.params }, { type: 'bend', b: bendPhysical(state.bend) }, { type: 'bridges', br: state.br }, seqMsg()],
  ccmap: [...RACK.flatMap((m) => m.items.filter((it) => it.f).map((it) => it.f)), ...BENDER.map((b) => b.f)] };`;
vm.runInContext(src, ctx);
const json = JSON.stringify(ctx.__out);
writeFileSync(out, `// Generated by plugin/tools/gen-default.mjs from site/js/app (defs.js, state.js, seq.js). Do not edit.
#pragma once
namespace shyoy { static const char* const DEFAULT_PATCH_JSON = R"SHYOY(${json})SHYOY"; }
`);
console.log('wrote', out.pathname, json.length, 'bytes');
